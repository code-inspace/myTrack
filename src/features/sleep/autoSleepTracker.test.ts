import {
  recordAppBackground,
  processAppForeground,
  scrubAutoGeneratedNaps,
  STORAGE_KEY_LAST_CLOSED,
} from "./autoSleepTracker";
import {
  getStoredSleepLog,
  saveStoredSleepLog,
  isNapTitle,
  syncTaskWithSleepNaps,
  removeTaskFromSleepNaps,
  computeSleepDuration,
} from "./actions";

describe("AutoSleepTracker", () => {
  let memoryStore: Record<string, string> = {};

  beforeEach(() => {
    memoryStore = {};
    const mockStorage = {
      getItem: (k: string) => memoryStore[k] || null,
      setItem: (k: string, v: string) => { memoryStore[k] = v; },
      removeItem: (k: string) => { delete memoryStore[k]; },
      clear: () => { memoryStore = {}; },
      get length() { return Object.keys(memoryStore).length; },
      key: (i: number) => Object.keys(memoryStore)[i] || null,
    };

    (globalThis as any).window = {
      localStorage: mockStorage,
      sessionStorage: mockStorage,
      dispatchEvent: () => true,
    };
    (globalThis as any).localStorage = mockStorage;
    (globalThis as any).sessionStorage = mockStorage;
  });

  it("records last closed timestamp and candidate bedtime on app background", () => {
    const eveningDate = new Date("2026-09-15T23:30:00");
    recordAppBackground(eveningDate);

    expect(localStorage.getItem(STORAGE_KEY_LAST_CLOSED)).toBe(eveningDate.toISOString());

    const log = getStoredSleepLog("2026-09-15");
    expect(log.bedtime).toBe("23:30");
  });

  it("automatically detects main sleep based on absence duration (e.g. 7h45)", () => {
    // 1. App closed at 23:30 on 2026-09-15
    const eveningDate = new Date("2026-09-15T23:30:00");
    recordAppBackground(eveningDate);

    // 2. App opened at 07:15 on 2026-09-16 (gap of 7h45m = 465 minutes)
    const morningDate = new Date("2026-09-16T07:15:00");
    const result = processAppForeground(morningDate);

    expect(result.detected).toBe(true);
    expect(result.bedtime).toBe("23:30");
    expect(result.wakeTime).toBe("07:15");
    expect(result.bedtimeDate).toBe("2026-09-15");
    expect(result.wakeDate).toBe("2026-09-16");
    expect(result.durationMinutes).toBe(465);

    // Check saved logs
    const yesterdayLog = getStoredSleepLog("2026-09-15");
    const todayLog = getStoredSleepLog("2026-09-16");

    expect(yesterdayLog.bedtime).toBe("23:30");
    expect(todayLog.wakeTime).toBe("07:15");
  });

  it("handles late-night closing (e.g. 01:15) and morning opening (08:30)", () => {
    // App closed at 01:15 AM on 2026-09-16
    const lateNightDate = new Date("2026-09-16T01:15:00");
    recordAppBackground(lateNightDate);

    // App opened at 08:30 AM on 2026-09-16 (gap of 7h15m = 435 minutes)
    const morningDate = new Date("2026-09-16T08:30:00");
    const result = processAppForeground(morningDate);

    expect(result.detected).toBe(true);
    expect(result.bedtime).toBe("01:15");
    expect(result.wakeTime).toBe("08:30");
    expect(result.bedtimeDate).toBe("2026-09-15"); // eve of wakeDate
    expect(result.wakeDate).toBe("2026-09-16");
  });

  it("does NOT automatically detect sleep for daytime absence (e.g. 11:00 -> 16:30)", () => {
    // App closed at 11:00
    const middayClose = new Date("2026-09-16T11:00:00");
    recordAppBackground(middayClose);

    // App opened at 16:30 (absence of 5h30m in daytime)
    const afternoonOpen = new Date("2026-09-16T16:30:00");
    const result = processAppForeground(afternoonOpen);

    expect(result.detected).toBe(false);
    expect(result.reason).toContain("Daytime absence");
  });

  it("does NOT automatically record a nap for absence < 3h (e.g. 75 min)", () => {
    // App closed at 13:30
    const closeDate = new Date("2026-09-16T13:30:00");
    recordAppBackground(closeDate);

    // App reopened at 14:45 (gap of 75 minutes = 1h15)
    const openDate = new Date("2026-09-16T14:45:00");
    const result = processAppForeground(openDate);

    expect(result.detected).toBe(false);
    expect(result.reason).toContain("Duration too short for overnight sleep");

    const log = getStoredSleepLog("2026-09-16");
    expect(log.naps?.length || 0).toBe(0);
  });

  it("correctly identifies nap keywords with isNapTitle", () => {
    expect(isNapTitle("Sieste")).toBe(true);
    expect(isNapTitle("sieste 20min")).toBe(true);
    expect(isNapTitle("Faire une sieste")).toBe(true);
    expect(isNapTitle("Micro-sieste")).toBe(true);
    expect(isNapTitle("Micro-siestes")).toBe(true);
    expect(isNapTitle("Power nap")).toBe(true);
    expect(isNapTitle("nap")).toBe(true);

    // Negative matches
    expect(isNapTitle("Assiette")).toBe(false);
    expect(isNapTitle("Réunion avec client")).toBe(false);
    expect(isNapTitle("Séance de sport")).toBe(false);
    expect(isNapTitle("")).toBe(false);
    expect(isNapTitle(null)).toBe(false);
  });

  it("automatically syncs task with 'sieste' in title to DailySleepLog.naps", async () => {
    const taskDate = "2026-09-16";
    const napTask = {
      id: "task-12345",
      title: "Sieste réparatrice",
      startTime: "13:30",
      endTime: "14:15",
      createdAt: `${taskDate}T12:00:00.000Z`,
      userId: "user-1",
    };

    // 1. Sync task creation
    await syncTaskWithSleepNaps(napTask, taskDate);

    const logAfterCreate = getStoredSleepLog(taskDate, "user-1");
    expect(logAfterCreate.naps?.length).toBe(1);
    expect(logAfterCreate.naps?.[0].startTime).toBe("13:30");
    expect(logAfterCreate.naps?.[0].endTime).toBe("14:15");
    expect(logAfterCreate.naps?.[0].taskId).toBe("task-12345");

    // 2. Sync task update (e.g. changed time)
    const updatedNapTask = {
      ...napTask,
      startTime: "14:00",
      endTime: "14:45",
    };
    await syncTaskWithSleepNaps(updatedNapTask, taskDate);

    const logAfterUpdate = getStoredSleepLog(taskDate, "user-1");
    expect(logAfterUpdate.naps?.length).toBe(1);
    expect(logAfterUpdate.naps?.[0].startTime).toBe("14:00");
    expect(logAfterUpdate.naps?.[0].endTime).toBe("14:45");

    // 3. Renamed task away from nap -> should remove nap
    const renamedTask = {
      ...napTask,
      title: "Lecture livre",
    };
    await syncTaskWithSleepNaps(renamedTask, taskDate);

    const logAfterRename = getStoredSleepLog(taskDate, "user-1");
    expect(logAfterRename.naps?.length).toBe(0);
  });

  it("removes nap when task is deleted via removeTaskFromSleepNaps", async () => {
    const taskDate = "2026-09-16";
    const napTask = {
      id: "task-999",
      title: "Micro-sieste",
      startTime: "15:00",
      endTime: "15:20",
      createdAt: `${taskDate}T12:00:00.000Z`,
      userId: "user-1",
    };

    await syncTaskWithSleepNaps(napTask, taskDate);
    expect(getStoredSleepLog(taskDate, "user-1").naps?.length).toBe(1);

    await removeTaskFromSleepNaps("task-999", taskDate, "user-1");
    expect(getStoredSleepLog(taskDate, "user-1").naps?.length).toBe(0);
  });

  it("does not overwrite manually validated bedtime or wake time", () => {
    // User already validated wakeTime = "06:45"
    saveStoredSleepLog({
      date: "2026-09-16",
      wakeTime: "06:45",
      wakeTimeValidated: true,
      bedtimeReminders: [],
      enableBedtimeReminders: true,
    });

    // App closed yesterday at 23:00
    recordAppBackground(new Date("2026-09-15T23:00:00"));

    // App opened at 09:00
    const morningDate = new Date("2026-09-16T09:00:00");
    processAppForeground(morningDate);

    const log = getStoredSleepLog("2026-09-16");
    expect(log.wakeTime).toBe("06:45"); // Preserved user's manually validated time!
  });

  it("accurately handles manual multi-day sleep editing starting one day and finishing the next day", () => {
    // 1. Save bedtime for day 1
    const startDate = "2026-09-15";
    const endDate = "2026-09-16";
    const startTime = "23:15";
    const endTime = "07:45";

    const startLog = getStoredSleepLog(startDate);
    saveStoredSleepLog({
      ...startLog,
      bedtime: startTime,
      bedtimeValidated: true,
      updatedAt: new Date().toISOString(),
    });

    const endLog = getStoredSleepLog(endDate);
    saveStoredSleepLog({
      ...endLog,
      wakeTime: endTime,
      wakeTimeValidated: true,
      updatedAt: new Date().toISOString(),
    });

    // 2. Verify both days hold their respective part of the cross-day sleep session
    const retrievedStart = getStoredSleepLog(startDate);
    const retrievedEnd = getStoredSleepLog(endDate);

    expect(retrievedStart.bedtime).toBe("23:15");
    expect(retrievedStart.bedtimeValidated).toBe(true);

    expect(retrievedEnd.wakeTime).toBe("07:45");
    expect(retrievedEnd.wakeTimeValidated).toBe(true);
  });

  it("scrubs legacy auto-generated naps while keeping task-linked and manual naps", () => {
    const testDate = "2026-09-16";
    const log = getStoredSleepLog(testDate);
    saveStoredSleepLog({
      ...log,
      naps: [
        { id: "nap-123456789", startTime: "14:00", endTime: "14:45" }, // legacy auto-generated nap
        { id: "task-nap-task1", taskId: "task1", startTime: "13:30", endTime: "14:00" }, // task nap
        { id: "nap_manual1", startTime: "15:00", endTime: "15:30" }, // manual nap
      ],
    });

    scrubAutoGeneratedNaps();

    const cleanedLog = getStoredSleepLog(testDate);
    expect(cleanedLog.naps?.length).toBe(2);
    expect(cleanedLog.naps?.some((n) => n.id === "nap-123456789")).toBe(false);
    expect(cleanedLog.naps?.some((n) => n.id === "task-nap-task1")).toBe(true);
    expect(cleanedLog.naps?.some((n) => n.id === "nap_manual1")).toBe(true);
  });

  it("correctly handles same-day morning bedtime (e.g. 03:00 -> 08:00)", () => {
    const bedtime = "03:00";
    const wakeTime = "08:00";
    const duration = computeSleepDuration(bedtime, wakeTime);

    expect(duration).not.toBeNull();
    expect(duration?.hours).toBe(5);
    expect(duration?.minutes).toBe(0);
    expect(duration?.text).toBe("5h 00m");

    // Saving bedtime for night of 2026-09-15 (eve of 2026-09-16) at 03:00
    const eveDate = "2026-09-15";
    const wakeDate = "2026-09-16";

    const eveLog = getStoredSleepLog(eveDate);
    saveStoredSleepLog({
      ...eveLog,
      bedtime,
      bedtimeValidated: true,
      updatedAt: new Date().toISOString(),
    });

    const wakeLog = getStoredSleepLog(wakeDate);
    saveStoredSleepLog({
      ...wakeLog,
      wakeTime,
      wakeTimeValidated: true,
      updatedAt: new Date().toISOString(),
    });

    const savedEve = getStoredSleepLog(eveDate);
    const savedWake = getStoredSleepLog(wakeDate);

    expect(savedEve.bedtime).toBe("03:00");
    expect(savedWake.wakeTime).toBe("08:00");
  });
});

